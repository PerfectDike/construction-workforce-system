const request = require('supertest')
const { app } = require('../../src/app')
const { prisma } = require('../../src/db')
const suite = process.env.RUN_CONNECTED_TESTS === '1' ? describe : describe.skip
suite('T102 connected scenario on a freshly seeded database', () => {
  afterAll(async () => prisma.$disconnect())
  test('plans, allocates, approves a correction and traces the report', async () => {
    const login = async email => (await request(app).post('/api/auth/login').send({ loginLabel: email, password: 'DemoPass123!' })).body.token
    const manager = await login('morgan.ellis@example.test'), officer = await login('casey.lane@example.test'), viewer = await login('robin.dale@example.test')
    const api = (verb, path, token) => request(app)[verb](path).set('Authorization', `Bearer ${token}`)
    const task = await api('get', '/api/tasks/T102', manager)
    expect(task.status).toBe(200)
    expect(task.body.predecessors[0].predecessor.sharedId).toBe('T101')
    const invalid = await api('patch', '/api/tasks/T102', manager).send({ predecessorIds: ['T201'] })
    expect(invalid.status).toBe(422)
    expect((await api('patch', '/api/tasks/T102', manager).send({ predecessorIds: ['T101'] })).status).toBe(200)
    for (const sharedId of ['P001', 'P002']) {
      const project = await prisma.project.findUniqueOrThrow({ where: { sharedId } })
      const plan = await api('post', `/api/projects/${project.id}/baselines`, manager).send({ reason: 'Initial plan' })
      expect(plan.status).toBe(201)
      if (sharedId === 'P001') {
        expect(plan.body.tasks.find(t => t.taskId === task.body.id).finishDate.slice(0, 10)).toBe('2026-11-06')
        await expect(prisma.baselineTask.update({ where: { baselineId_taskId: { baselineId: plan.body.id, taskId: task.body.id } }, data: { title: 'Changed' } })).rejects.toThrow()
      }
    }
    const assign = (workerId, taskId, workDate, hours) => api('post', '/api/allocations', manager).send({ workerId, taskId, workDate, hours })
    const first = await assign('W001', 'T102', '2026-11-04', 6)
    expect(first.status).toBe(201)
    expect((await assign('W001', 'T201', '2026-11-04', 2)).status).toBe(201)
    const excess = await assign('W001', 'T102', '2026-11-04', 1)
    expect(excess.status).toBe(422); expect(excess.body.error.code).toBe('OVER_CAPACITY')
    const wrongSkill = await assign('W002', 'T103', '2026-11-11', 1)
    expect(wrongSkill.body.error.code).toBe('SKILL_MISMATCH')
    const original = await api('post', '/api/site-updates', officer).send({ allocationId: first.body.id, workDate: '2026-11-04', recordedHours: 4 })
    expect(original.status).toBe(201)
    expect((await api('post', `/api/site-updates/${original.body.id}/approve`, officer).send({})).status).toBe(403)
    expect((await api('post', `/api/site-updates/${original.body.id}/approve`, manager).send({})).status).toBe(200)
    const correction = await api('post', '/api/site-updates', officer).send({ allocationId: first.body.id, workDate: '2026-11-04', recordedHours: 3, actualFinishDate: '2026-11-09', supersedesId: original.body.id })
    expect(correction.status).toBe(201)
    expect(Number((await api('get', '/api/tasks/T102/site-updates', viewer)).body[0].recordedHours)).toBe(4)
    expect((await api('post', `/api/site-updates/${correction.body.id}/approve`, manager).send({})).status).toBe(200)
    const report = await api('get', '/api/reports/tasks/T102', viewer)
    expect(report.body).toMatchObject({ finishVarianceDays: 3, plannedHours: 6, recordedHours: 3, hoursStatus: 'reported' })
    expect(report.body.sources.allocationIds).toContain(first.body.id)
    expect(report.body.sources.updateIds).toContain(correction.body.id)
    const missing = await api('get', '/api/reports/tasks/T103', viewer)
    expect(missing.body.recordedHours).toBeNull()
    const allocation = await assign('W003', 'T103', '2026-11-11', 5)
    expect(allocation.status).toBe(201)
    const zero = await api('post', '/api/site-updates', officer).send({ allocationId: allocation.body.id, workDate: '2026-11-11', recordedHours: 0 })
    expect(zero.status).toBe(201)
    expect((await api('post', `/api/site-updates/${zero.body.id}/approve`, manager).send({})).status).toBe(200)
    expect((await api('get', '/api/reports/tasks/T103', viewer)).body.recordedHours).toBe(0)
  })
})

